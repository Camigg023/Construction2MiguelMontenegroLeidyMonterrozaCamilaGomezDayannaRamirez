package src.main.java.app.domain.model.emuns;

/**
 * Enum que representa los tipos de signos vitales que puede registrar una enfermera.
 */
public enum VitalSignType {
    BLOOD_PRESSURE,   // Presión arterial
    TEMPERATURE,      // Temperatura corporal
    HEART_RATE,       // Frecuencia cardíaca o pulso
    OXYGEN_SATURATION,// Nivel de oxígeno en sangre
    RESPIRATORY_RATE  // Frecuencia respiratoria
}
